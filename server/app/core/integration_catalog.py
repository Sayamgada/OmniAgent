def get_auth_option(service: str, option_id: str | None = None) -> dict:
    """Returns the chosen auth_option dict for a service, or its default if option_id is omitted."""
    entry = INTEGRATION_CATALOG.get(service)
    if not entry:
        return None
    target = option_id or entry["default_option"]
    for opt in entry["auth_options"]:
        if opt["option_id"] == target:
            return opt
    return None